#!/usr/bin/env python3
"""Third-party notices for the four apps, generated from legal/third-party.json.

  scripts/legal/notices.py generate               write legal/THIRD_PARTY_NOTICES.md
  scripts/legal/notices.py check                  fail if THIRD_PARTY_NOTICES.md is out of date or a license file is missing
  scripts/legal/notices.py check-ffmpeg           fail if the FFmpeg component versions differ from scripts/ffmpeg/versions.sh
  scripts/legal/notices.py check-packages FILE..  fail if a .NET build ships a package or runtime pack the manifest doesn't
                                                  list at that exact version (FILE: *.deps.json or obj/project.assets.json)

Standard library only, so it runs on every CI runner.
"""
import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "legal" / "third-party.json"
LICENSES = ROOT / "legal" / "licenses"
OUTPUT = ROOT / "legal" / "THIRD_PARTY_NOTICES.md"


# Windows consoles and CI logs may default to a legacy code page; the check marks must not crash the script.
for stream in (sys.stdout, sys.stderr):
    try:
        stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass


def problem(message):
    """Prints a problem; on GitHub Actions also as an annotation, so it's visible on the run page."""
    if os.environ.get("GITHUB_ACTIONS") == "true":
        print(f"::error title=third-party notices::{message}", flush=True)
    print(f"✗ {message}", file=sys.stderr)


def load():
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def anchor(path):
    return "license-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def render(data):
    apps = data["apps"]
    components = data["components"]
    lines = [
        "# Third-party notices",
        "",
        "<!-- Generated by scripts/legal/notices.py from legal/third-party.json. Don't edit by hand. -->",
        "",
        "Potion and Potion Dropper are MIT-licensed (see `LICENSE`). They include the third-party software listed below.",
        "Each component keeps its own license; the full texts follow at the end, unmodified from each component's",
        "source archive, package or repository at the shipped version.",
        "",
        "FFmpeg and the libraries built into it ship as separate programs (`ffmpeg`, `ffprobe`), not linked into the",
        "apps. The exact source archives (pinned by SHA-256) and the build scripts are in `scripts/ffmpeg/` and are",
        "attached to each release, so the programs can be rebuilt and replaced.",
        "",
        "## Summary",
        "",
        "| Component | Version | License | " + " | ".join(apps.values()) + " |",
        "|---|---|---|" + "---|" * len(apps),
    ]
    for c in components:
        used = " | ".join("✓" if key in c["apps"] else "" for key in apps)
        lines.append(f"| {c['name']} | {c['version']} | {c['license']} | {used} |")
    lines += ["", "## Components", ""]
    for c in components:
        lines += [f"### {c['name']} {c['version']}", ""]
        lines.append(f"- License: {c['license']}")
        if c.get("copyright"):
            lines.append(f"- Copyright: {c['copyright']}")
        lines.append(f"- Source: {c['source']}")
        lines.append(f"- Used in: {', '.join(apps[a] for a in c['apps'])}")
        lines.append(f"- How it's used: {c['use']}")
        if c.get("packages"):
            lines.append(f"- Packages: {', '.join('`' + p + '`' for p in c['packages'])}")
        if c["licenseFiles"]:
            links = ", ".join(f"[{pathlib.PurePosixPath(f).name}](#{anchor(f)})" for f in c["licenseFiles"])
            lines.append(f"- License text: {links}")
        lines.append("")
    lines += ["## License texts", ""]
    seen = []
    for c in components:
        for f in c["licenseFiles"]:
            if f in seen:
                continue
            seen.append(f)
            text = (LICENSES / f).resolve().read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").rstrip()
            lines += [f'<a id="{anchor(f)}"></a>', "", f"### {pathlib.PurePosixPath(f).name}", "", "~~~~text", text, "~~~~", ""]
    return "\n".join(lines).rstrip() + "\n"


def check_files(data):
    missing = [f for c in data["components"] for f in c["licenseFiles"] if not (LICENSES / f).resolve().is_file()]
    for f in missing:
        problem(f"missing license file: legal/licenses/{f}")
    fenced = [f for c in data["components"] for f in c["licenseFiles"]
              if (LICENSES / f).resolve().is_file() and "~~~~" in (LICENSES / f).resolve().read_text(encoding="utf-8", errors="replace")]
    for f in fenced:
        problem(f"{f} contains '~~~~', which would break the Markdown fence")
    return not missing and not fenced


def cmd_generate():
    data = load()
    if not check_files(data):
        return 1
    OUTPUT.write_text(render(data), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


def cmd_check():
    data = load()
    if not check_files(data):
        return 1
    if (ROOT / "legal" / "LICENSE").read_bytes() != (ROOT / "LICENSE").read_bytes():
        problem("legal/LICENSE differs from LICENSE (spec Part 6.4 keeps a copy in legal/). Copy LICENSE over it.")
        return 1
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != render(data):
        problem("legal/THIRD_PARTY_NOTICES.md is out of date. Run: scripts/legal/notices.py generate")
        return 1
    print("✓ third-party notices are up to date")
    return 0


def cmd_check_ffmpeg():
    versions = (ROOT / "scripts" / "ffmpeg" / "versions.sh").read_text(encoding="utf-8")
    pinned = dict(re.findall(r"^([A-Z0-9]+)_VERSION=([^\s]+)", versions, re.M))
    names = {"FFmpeg": "FFMPEG", "LAME": "LAME", "Opus": "OPUS", "libogg": "OGG", "libvorbis": "VORBIS",
             "libvpx": "VPX", "libwebp": "WEBP", "SVT-AV1": "SVTAV1", "zlib": "ZLIB"}
    ok = True
    for c in load()["components"]:
        key = names.get(c["name"])
        if key is None:
            continue
        if pinned.get(key) != c["version"]:
            problem(f"{c['name']}: third-party.json says {c['version']}, versions.sh says {pinned.get(key)}")
            ok = False
    if ok:
        print("✓ FFmpeg component versions match scripts/ffmpeg/versions.sh")
    return 0 if ok else 1


def shipped_packages(path):
    """(packages, runtime packs) from a *.deps.json (what a build ships) or project.assets.json (what a restore resolved)."""
    data = json.loads(pathlib.Path(path).read_text(encoding="utf-8-sig"))
    packages, packs = set(), set()
    for key, info in data.get("libraries", {}).items():
        kind = info.get("type")
        if kind == "package":
            packages.add(key)
        elif kind == "runtimepack":
            name = key.split("/")[0]
            packs.add(name[len("runtimepack."):] if name.startswith("runtimepack.") else name)
    return packages, packs


def cmd_check_packages(paths):
    if not paths:
        problem("no deps.json or project.assets.json files were given (did the build output move?)")
        return 1
    data = load()
    listed = {p for c in data["components"] for p in c.get("packages", [])}
    packs = {p for c in data["components"] for p in c.get("runtimePacks", [])}
    build_only = set(data.get("buildOnlyPackages", []))
    ok = True
    for path in paths:
        packages, runtime = shipped_packages(path)
        for package in sorted(packages):
            if package in listed or package.split("/")[0] in build_only:
                continue
            problem(f"{path}: {package} isn't in legal/third-party.json (add it with its license, or update the version)")
            ok = False
        for pack in sorted(runtime):
            if not any(pack.startswith(prefix) for prefix in packs):
                problem(f"{path}: runtime pack {pack} isn't in legal/third-party.json")
                ok = False
    if ok:
        print(f"✓ every shipped .NET package is listed ({len(paths)} file(s) checked)")
    return 0 if ok else 1


def main(argv):
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    command = argv[1]
    if command == "generate":
        return cmd_generate()
    if command == "check":
        return cmd_check()
    if command == "check-ffmpeg":
        return cmd_check_ffmpeg()
    if command == "check-packages" and len(argv) > 2:
        return cmd_check_packages(argv[2:])
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
